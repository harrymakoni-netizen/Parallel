"""Write docs/engine-matrix.md from the engine capability records and live installation checks.

The matrix is generated, not hand-written, so it cannot drift from what the adapters declare and
what this host actually provides. Run with:  uv run python scripts/engine_matrix.py
"""

from __future__ import annotations

import platform
import socket
import sys
from datetime import UTC, datetime
from pathlib import Path

from parallel_engines.registry import all_adapters

OUT = Path(__file__).resolve().parents[1] / "docs" / "engine-matrix.md"

STATUS = {
    "verified": "Verified",
    "awaiting_environment": "Awaiting environment verification",
    "not_verified": "Not verified",
}


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def main() -> int:
    adapters = all_adapters()
    checks = {}
    for a in adapters:
        for mode in a.capability.execution_modes:
            try:
                checks[(a.capability.engine_id, mode)] = a.check_installation(mode)
            except Exception as e:  # a failing check is reported, never hidden
                checks[(a.capability.engine_id, mode)] = e

    lines = [
        "# Engine matrix",
        "",
        f"Generated by `scripts/engine_matrix.py` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC "
        f"on `{socket.gethostname()}` ({platform.system()} {platform.machine()}, Python {platform.python_version()}).",
        "Availability is what this host reported when the matrix was generated; the Engine Library page "
        "shows the live state of each installation.",
        "",
        "Verification status follows the implementation-status categories: *Verified* means an automated test "
        "ran the pinned engine on the platform named and checked its outputs against native results; "
        "*Awaiting environment verification* means the adapter is implemented and tested against recorded or "
        "generated inputs, but the engine itself was not available to run; *Not verified* means no installation "
        "of that product has been tested.",
        "",
        "## Summary",
        "",
        "| Engine | Role | Licence | Execution modes | Tested version | Status | This host |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for a in adapters:
        c = a.capability
        tested = "; ".join(t.version for t in c.tested_versions) or "none"
        status = "; ".join(STATUS.get(t.status, t.status) for t in c.tested_versions) or "Not verified"
        host = []
        for mode in c.execution_modes:
            r = checks[(c.engine_id, mode)]
            host.append(f"{mode}: {'check failed' if isinstance(r, Exception) else r.availability.value.replace('_', ' ')}")
        lines.append(
            f"| {cell(c.name)} | {cell(c.role)} | {cell(c.licence.name or c.licence.kind)} | "
            f"{', '.join(str(m) for m in c.execution_modes)} | {cell(tested)} | {cell(status)} | {cell('; '.join(host))} |"
        )

    for a in adapters:
        c = a.capability
        lines += ["", f"## {c.name} (`{c.engine_id}`)", "", c.role, ""]
        lines += [
            f"- **Vendor:** {c.vendor}",
            f"- **Licence:** {c.licence.name or c.licence.kind}"
            + (" (licence key required)" if c.licence.requires_key else "")
            + (f". {c.licence.note}" if c.licence.note else ""),
            f"- **Adapter version:** {a.adapter_version}",
            f"- **Pinned version:** {c.pinned_version or 'none (operator-supplied installation)'}",
            f"- **Disciplines:** {', '.join(c.disciplines)}",
            f"- **Dimensions:** {', '.join(c.dimensions)}",
            f"- **Model input:** {'; '.join(c.model_formats_in)}",
            f"- **Outputs:** {'; '.join(c.model_formats_out)}",
            f"- **Units in / out:** {', '.join(f'{k} {v}' for k, v in c.input_units.items())} / "
            f"{', '.join(f'{k} {v}' for k, v in c.output_units.items())}",
            f"- **Runtime:** {'; '.join(c.runtime_requirements)}",
            f"- **Cancellation:** {c.cancellation}",
            f"- **Resource estimate:** {c.resource_estimate}",
        ]
        if c.companion_tools:
            lines.append(f"- **Companion tools:** {'; '.join(c.companion_tools)}")
        lines += ["", "**Tested versions**", ""]
        for t in c.tested_versions:
            lines.append(
                f"- {t.version} on {t.platform}: {STATUS.get(t.status, t.status)}"
                + (f" ({t.verified_on})" if t.verified_on else "")
                + (f". Evidence: `{t.evidence}`" if t.evidence else "")
            )
        lines += ["", "**Installation check on this host**", ""]
        for mode in c.execution_modes:
            r = checks[(c.engine_id, mode)]
            if isinstance(r, Exception):
                lines.append(f"- {mode}: check failed ({type(r).__name__}: {r})")
                continue
            detail = "; ".join(r.details)
            lines.append(
                f"- {mode}: **{r.availability.value.replace('_', ' ')}**"
                + (f", detected {r.detected_version}" if r.detected_version else "")
                + (f". {detail}" if detail else "")
                + (f" Next step: {r.remedy}" if r.remedy else "")
            )
        lines += ["", "**Limitations**", ""] + [f"- {x}" for x in c.limitations]
        if c.official_docs:
            lines += ["", "**Documentation:** " + ", ".join(c.official_docs)]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
