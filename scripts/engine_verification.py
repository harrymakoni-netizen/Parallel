"""Run each managed engine's reference workflow and write docs/engine-verification.md: a documented
execution record (spec 30.2) of every native cross-check, with the normalised and native values, the
tolerance and why that tolerance is appropriate.

    uv run python scripts/engine_verification.py

The same reference workflows run in the engine tests (packages/engines/tests); this script records
their cross-checks in a readable form. Engines that are not ready on this host are listed as such.
"""

from __future__ import annotations

import platform
import socket
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from parallel_contracts.engines import Availability
from parallel_engines import reference_models as rm
from parallel_engines.base import NullMonitor, RunContext, RunWorkspace
from parallel_engines.registry import get_adapter

OUT = Path(__file__).resolve().parents[1] / "docs" / "engine-verification.md"

WORKFLOWS = [
    ("jupedsim", "Level mine section, 60 people, pre-movement 5 to 15 s, 300 s horizon",
     lambda: (rm.mine_section_model(), rm.pedestrian_scenario(is_baseline=True, max_duration_s=300,
                                                              pre_movement=rm.premovement(5, 15)))),
    ("sumo", "Crossroads corridor, priority junction, 450 scheduled trips over one hour",
     lambda: (rm.crossroads_model(), rm.traffic_scenario(is_baseline=True))),
    ("swmm", "Four-junction network, 60 min design storm",
     lambda: (rm.drainage_model(), rm.drainage_scenario(is_baseline=True))),
    ("epanet", "Water network of 6 junctions and 9 pipes, 24 h extended period",
     lambda: (rm.water_network_model(), rm.water_scenario(is_baseline=True))),
    ("simpy", "Site deliveries, reference scenario with one replication",
     lambda: (rm.site_operations_model(), rm.operations_scenario(is_baseline=True))),
    ("openfoam", "Two-dimensional site wind around obstacles, 800 iterations",
     lambda: (rm.site_wind_model(), rm.cfd_scenario(iterations=800))),
]


def fmt(v) -> str:
    if v is None:
        return "none"
    if isinstance(v, float):
        return f"{v:.6g}"
    return str(v)


def main() -> int:
    lines = [
        "# Engine verification record",
        "",
        f"Generated by `scripts/engine_verification.py` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC on "
        f"`{socket.gethostname()}` ({platform.system()} {platform.machine()}, Python {platform.python_version()}).",
        "",
        "Each managed engine ran its reference workflow (the same one its tests use). Every normalised value",
        "that can be recomputed from the engine's own native output is cross-checked: a check passes when",
        "`|normalised - native| <= max(absolute tolerance, relative tolerance x |native|)`. The rationale",
        "records why each tolerance is appropriate. Licensed and operator-run engines are verified by",
        "their file-exchange import tests instead; see [validation.md](validation.md#engines).",
    ]
    failures = 0
    for engine_id, label, build in WORKFLOWS:
        adapter = get_adapter(engine_id)
        check = adapter.check_installation()
        lines += ["", f"## {adapter.capability.name}", "", f"Workflow: {label}.", ""]
        if check.availability != Availability.ready:
            lines.append(f"Not run on this host: {check.availability.value} ({'; '.join(check.details)}).")
            continue
        model, scenario = build()
        with tempfile.TemporaryDirectory() as td:
            ws = RunWorkspace(Path(td)).create()
            ctx = RunContext(run_id="verification", workspace=ws, model=model, scenario=scenario, seed=42)
            prepared = adapter.prepare_inputs(ctx)
            execution = adapter.execute(ctx, prepared, NullMonitor())
            result = adapter.normalise_results(ctx, prepared, execution)
            result.check_registered()
        passed = sum(1 for c in result.crosschecks if c["passed"])
        failures += len(result.crosschecks) - passed
        lines += [
            f"Engine {execution.engine_version}, adapter {adapter.adapter_version}; {len(result.metrics)} metrics, "
            f"all registered; {passed} of {len(result.crosschecks)} cross-checks passed.",
            "",
            "| Cross-check | Normalised | Native | Tolerance (abs / rel) | Result | Why this tolerance |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for c in result.crosschecks:
            why = (c.get("tolerance_rationale") or "").replace("|", "\\|")
            lines.append(
                f"| {c['name']} | {fmt(c.get('normalised'))} | {fmt(c.get('native'))} | "
                f"{fmt(c.get('abs_tolerance'))} / {fmt(c.get('rel_tolerance'))} | "
                f"{'Passed' if c['passed'] else 'Failed'} | {why} |"
            )
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({failures} failed cross-checks)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
