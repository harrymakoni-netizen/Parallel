"""Regenerate the reference documents that are derived from code:

- docs/metrics.md         the metric registry (definitions, calculations, sources, missing-value rules)
- docs/api.md             the HTTP API by area, from the OpenAPI document
- docs/api/openapi.json   the OpenAPI document itself
- docs/engine-matrix.md   engine capabilities and this host's installation checks

Run with:  uv run python scripts/reference_docs.py
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def cell(s: object) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def metrics() -> None:
    from parallel_metrics.registry import METRICS

    by = defaultdict(list)
    for m in METRICS.values():
        by[m.discipline].append(m)
    lines = [
        "# Metric catalogue",
        "",
        "Generated by `scripts/reference_docs.py` from `packages/metrics` (the metric registry). Every value an",
        "engine adapter reports must use one of these identifiers; an adapter that emits an undocumented",
        "metric fails its run. Each metric states how it is calculated, which engine outputs it comes from,",
        "its spatial extent and time interval, and what is reported when it cannot be computed (unattained",
        "or unavailable values are reported as such and never estimated).",
        "",
        f"{len(METRICS)} metrics in {len(by)} disciplines.",
    ]
    for disc in sorted(by):
        lines += ["", f"## {disc.replace('_', ' ').capitalize()}", ""]
        lines += ["| Identifier | Name | Unit | Definition | Calculation | Source outputs | Extent / interval | When missing |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for m in sorted(by[disc], key=lambda x: x.id):
            ent = " (per entity)" if m.per_entity else ""
            lines.append(
                f"| `{m.id}` | {cell(m.name)}{ent} | {cell(m.unit)} | {cell(m.definition)} | {cell(m.calculation)} | "
                f"{cell('; '.join(m.source_outputs))} | {cell(m.extent)}; {cell(m.time_interval)} | {cell(m.missing_value_rule)} |"
            )
    (DOCS / "metrics.md").write_text("\n".join(lines) + "\n")


def api() -> None:
    from parallel_api.main import create_app

    spec = create_app().openapi()
    (DOCS / "api").mkdir(exist_ok=True)
    (DOCS / "api" / "openapi.json").write_text(json.dumps(spec, indent=1) + "\n")
    by = defaultdict(list)
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            by[(op.get("tags") or ["other"])[0]].append((path, method.upper(), op.get("summary", "")))
    n = sum(len(v) for v in by.values())
    lines = [
        "# HTTP API",
        "",
        "Generated by `scripts/reference_docs.py`. The machine-readable OpenAPI document is",
        "[`docs/api/openapi.json`](api/openapi.json); a running API also serves interactive documentation at",
        "`/api/docs` and the live document at `/api/v1/openapi.json`.",
        "",
        "All endpoints are under `/api/v1` and, apart from sign-in, configuration and health, require a bearer",
        "token (`Authorization: Bearer <token>`). Authorisation is decided on the server for every request:",
        "organisation and project roles, and case assignment for CrashLens records. Errors use one shape:",
        '`{"error": {"code": "...", "message": "...", "details": ...}}`. Long-running work (reconstructions,',
        "runs, reports) is asynchronous: the create call returns a job record, and progress is available by",
        "polling or as server-sent events on the `/events` endpoints.",
        "",
        f"{n} operations in {len(by)} areas.",
    ]
    for tag in sorted(by):
        lines += ["", f"## {tag.capitalize()}", "", "| Method | Path | Summary |", "| --- | --- | --- |"]
        for path, method, summary in sorted(by[tag]):
            lines.append(f"| {method} | `{path}` | {cell(summary)} |")
    (DOCS / "api.md").write_text("\n".join(lines) + "\n")


def main() -> int:
    metrics()
    api()
    sys.path.insert(0, str(ROOT / "scripts"))
    import engine_matrix

    engine_matrix.main()
    print("wrote docs/metrics.md, docs/api.md, docs/api/openapi.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
