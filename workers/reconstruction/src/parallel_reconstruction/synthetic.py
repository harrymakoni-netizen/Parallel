"""Synthetic capture generator for demonstrations and tests (clearly labelled synthetic material).

Renders a textured scene with a NumPy ray caster from a known camera path:
a ground plane, textured boxes and two checkerboard survey targets whose
positions are known exactly. Produces images, an MP4 walk-around video and a
ground-truth file (camera centres, intrinsics, target positions, object
dimensions) used to establish scale and check measurements against truth.

Nothing here is presented as a real capture: every output is tagged
``synthetic`` and the ground truth is recorded as synthetic provenance.
"""

from __future__ import annotations

import json
import subprocess
import zlib
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np
from PIL import Image


@dataclass
class Box:
    name: str
    center: tuple[float, float, float]
    size: tuple[float, float, float]
    texture_seed: int
    tint: tuple[float, float, float] = (1.0, 1.0, 1.0)


@dataclass
class Target:
    """Coded survey target: a unique 6x6 binary grid inside a black border (unique features for SfM).

    Sized so code cells stay well above SIFT's feature scale at ~10 m capture distance.
    """

    name: str
    center: tuple[float, float]
    size_m: float = 1.6


@dataclass
class SyntheticScene:
    name: str
    extent_m: float = 30.0  # ground texture spans +/- extent without repetition
    boxes: list[Box] = field(default_factory=list)
    targets: list[Target] = field(default_factory=list)
    ground_seed: int = 11
    lane_markings: bool = False


def road_scene() -> SyntheticScene:
    """Controlled training scene for CrashLens: two vehicles at rest, a road with markings and two survey targets."""
    return SyntheticScene(
        name="training-road-scene",
        lane_markings=True,
        boxes=[
            Box("vehicle_1", (2.5, 1.2, 0.75), (4.4, 1.8, 1.5), 3, (0.85, 0.3, 0.3)),
            Box("vehicle_2", (-2.2, -1.6, 0.8), (4.7, 1.9, 1.6), 5, (0.3, 0.45, 0.85)),
            Box("barrier", (0.0, 5.5, 0.5), (8.0, 0.4, 1.0), 7, (0.8, 0.8, 0.75)),
            Box("signal_cabinet", (-5.5, 4.0, 0.7), (0.8, 0.6, 1.4), 9, (0.5, 0.6, 0.5)),
        ],
        targets=[Target("target_A", (-4.0, -4.5)), Target("target_B", (5.0, -4.0))],
    )


def room_scene() -> SyntheticScene:
    """Small indoor-like scene with crates (room-scale reconstruction demonstration)."""
    return SyntheticScene(
        name="crate-room",
        boxes=[Box("crate_1", (1.5, 1.0, 0.5), (1.2, 1.0, 1.0), 13, (0.8, 0.65, 0.4)),
               Box("crate_2", (-1.8, 0.5, 0.6), (1.0, 1.4, 1.2), 17, (0.6, 0.7, 0.5)),
               Box("cabinet", (0.0, -2.5, 0.9), (2.0, 0.6, 1.8), 19, (0.55, 0.55, 0.65))],
        targets=[Target("target_A", (-3.0, 2.5)), Target("target_B", (3.0, 2.5))],
    )


def _texture(seed: int, size: int = 512) -> np.ndarray:
    """Multi-scale noise with random blobs and lines: rich, non-repeating features for SIFT."""
    rng = np.random.default_rng(seed)
    tex = np.zeros((size, size), dtype=np.float32)
    for octave, amp in ((8, 0.5), (32, 0.25), (128, 0.15), (512, 0.1)):
        small = rng.random((octave, octave)).astype(np.float32)
        img = Image.fromarray((small * 255).astype(np.uint8)).resize((size, size), Image.BICUBIC)
        tex += amp * (np.asarray(img, dtype=np.float32) / 255.0)
    yy, xx = np.mgrid[0:size, 0:size]
    for _ in range(60):
        cx, cy, r = rng.integers(0, size, 2).tolist() + [int(rng.integers(4, 28))]
        tex[(xx - cx) ** 2 + (yy - cy) ** 2 < r * r] = rng.random()
    for _ in range(20):
        y0 = int(rng.integers(0, size))
        tex[y0:y0 + int(rng.integers(1, 4)), :] *= 0.6
    tex = (tex - tex.min()) / (tex.max() - tex.min() + 1e-9)
    rgb = np.stack([tex, tex * 0.9 + 0.05 * rng.random(), tex * 0.8 + 0.1 * rng.random()], axis=-1)
    return np.clip(rgb, 0, 1)


def _look_at(cam: np.ndarray, target: np.ndarray) -> np.ndarray:
    """World-from-camera rotation (OpenCV camera: +X right, +Y down, +Z forward)."""
    fwd = target - cam
    fwd /= np.linalg.norm(fwd)
    right = np.cross(fwd, np.array([0.0, 0.0, 1.0]))
    right /= np.linalg.norm(right)
    down = np.cross(fwd, right)
    return np.stack([right, down, fwd], axis=1)


@dataclass
class GroundTruth:
    scene: str
    width: int
    height: int
    focal_px: float
    camera_centres: list[list[float]]
    frame_names: list[str]
    targets: dict[str, list[float]]
    boxes: dict[str, dict]
    note: str = "Synthetic ground truth generated by Parallel; not a real capture."


class Renderer:
    def __init__(self, scene: SyntheticScene, width: int = 640, height: int = 480, fov_deg: float = 65.0):
        self.scene = scene
        self.w, self.h = width, height
        self.f = 0.5 * width / np.tan(np.radians(fov_deg) / 2)
        self.ground_tex = _texture(scene.ground_seed, 2048)
        self.box_tex = {b.name: _texture(b.texture_seed) for b in scene.boxes}
        self._codes: dict[str, np.ndarray] = {}
        ys, xs = np.mgrid[0:height, 0:width].astype(np.float32)
        self.dirs_cam = np.stack([(xs + 0.5 - width / 2) / self.f, (ys + 0.5 - height / 2) / self.f,
                                  np.ones_like(xs)], axis=-1).reshape(-1, 3)
        self.light = np.array([0.4, -0.3, 0.85])
        self.light /= np.linalg.norm(self.light)

    def _ground_colour(self, p: np.ndarray) -> np.ndarray:
        ext = self.scene.extent_m
        u = np.clip((p[:, 0] + ext) / (2 * ext), 0.0, 1.0)
        v = np.clip((p[:, 1] + ext) / (2 * ext), 0.0, 1.0)
        n = self.ground_tex.shape[0]
        col = self.ground_tex[(v * (n - 1)).astype(int), (u * (n - 1)).astype(int)] * 0.55 + 0.15
        if self.scene.lane_markings:
            dashed = (np.abs(p[:, 1] - 0.0) < 0.08) & (((p[:, 0] + 100) % 4.0) < 2.0)
            edges = (np.abs(np.abs(p[:, 1]) - 3.4) < 0.07)
            col[dashed | edges] = [0.92, 0.92, 0.88]
        for t in self.scene.targets:
            dx, dy = p[:, 0] - t.center[0], p[:, 1] - t.center[1]
            inside = (np.abs(dx) < t.size_m / 2) & (np.abs(dy) < t.size_m / 2)
            cells = 8  # 6x6 code + 1-cell black border
            ix = np.clip(((dx + t.size_m / 2) / t.size_m * cells).astype(int), 0, cells - 1)
            iy = np.clip(((dy + t.size_m / 2) / t.size_m * cells).astype(int), 0, cells - 1)
            code = self._codes.setdefault(t.name, np.random.default_rng(zlib.crc32(t.name.encode())).random((cells, cells)) > 0.5)
            border = (ix == 0) | (iy == 0) | (ix == cells - 1) | (iy == cells - 1)
            white = code[iy, ix] & ~border
            col[inside & white] = [0.97, 0.97, 0.97]
            col[inside & ~white] = [0.05, 0.05, 0.05]
        return col

    def render(self, cam: np.ndarray, target: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        r_wc = _look_at(cam, target)
        d = self.dirs_cam @ r_wc.T
        d /= np.linalg.norm(d, axis=1, keepdims=True)
        n = len(d)
        t_best = np.full(n, np.inf)
        col = np.zeros((n, 3))
        normal = np.zeros((n, 3))
        # sky (gradient, few features): far background
        sky = np.clip(0.55 + 0.4 * d[:, 2:3], 0, 1) * np.array([0.6, 0.75, 0.95])
        col[:] = sky
        # ground plane z = 0
        with np.errstate(divide="ignore", invalid="ignore"):
            tg = -cam[2] / d[:, 2]
        hit = (tg > 0) & np.isfinite(tg)
        p = cam + d * tg[:, None]
        hit &= (np.abs(p[:, 0]) < self.scene.extent_m) & (np.abs(p[:, 1]) < self.scene.extent_m)
        t_best[hit] = tg[hit]
        col[hit] = self._ground_colour(p[hit])
        normal[hit] = [0, 0, 1]
        # boxes (slab method)
        for b in self.scene.boxes:
            c, s = np.array(b.center), np.array(b.size) / 2
            lo, hi = c - s, c + s
            with np.errstate(divide="ignore", invalid="ignore"):
                inv = 1.0 / d
                t1, t2 = (lo - cam) * inv, (hi - cam) * inv
            tmin = np.max(np.minimum(t1, t2), axis=1)
            tmax = np.min(np.maximum(t1, t2), axis=1)
            bh = (tmax >= tmin) & (tmin > 0) & (tmin < t_best)
            if not bh.any():
                continue
            q = cam + d[bh] * tmin[bh, None]
            rel = (q - c) / s
            axis = np.argmax(np.abs(rel), axis=1)
            nrm = np.zeros_like(q)
            nrm[np.arange(len(q)), axis] = np.sign(rel[np.arange(len(q)), axis])
            # UV on the face from the two other axes
            other = np.array([[1, 2], [0, 2], [0, 1]])[axis]
            u = (rel[np.arange(len(q)), other[:, 0]] + 1) / 2
            v = (rel[np.arange(len(q)), other[:, 1]] + 1) / 2
            tex = self.box_tex[b.name]
            m = tex.shape[0] - 1
            face_offset = (axis * 2 + (nrm[np.arange(len(q)), axis] > 0)) * 37
            colour = tex[((v * m).astype(int) + face_offset) % (m + 1), ((u * m).astype(int) + face_offset) % (m + 1)]
            t_best[bh] = tmin[bh]
            col[bh] = colour * np.array(b.tint)
            normal[bh] = nrm
        lit = np.clip(normal @ self.light, 0, 1)
        has_n = np.linalg.norm(normal, axis=1) > 0
        col[has_n] *= (0.45 + 0.55 * lit[has_n])[:, None]
        img = (np.clip(col, 0, 1).reshape(self.h, self.w, 3) * 255).astype(np.uint8)
        return img, r_wc


def orbit(n: int, radius: float, height: float, z_look: float = 0.6, wobble: float = 0.4,
          start_deg: float = 0.0) -> list[tuple[np.ndarray, np.ndarray]]:
    out = []
    for i in range(n):
        a = np.radians(start_deg) + 2 * np.pi * i / n
        r = radius + wobble * np.sin(3 * a)
        cam = np.array([r * np.cos(a), r * np.sin(a), height + 0.3 * np.sin(2 * a)])
        target = np.array([0.4 * np.cos(a + 1.0), 0.4 * np.sin(a + 1.0), z_look])
        out.append((cam, target))
    return out


def generate(scene: SyntheticScene, out_dir: Path, n_frames: int = 72, radius: float = 10.0, height: float = 3.2,
             width: int = 640, height_px: int = 480, video: bool = True, fps: int = 6,
             blur_every: int = 0) -> GroundTruth:
    """Render frames (optionally with deliberately blurred frames) and an MP4; write ground_truth.json."""
    out_dir.mkdir(parents=True, exist_ok=True)
    frames_dir = out_dir / "frames"
    frames_dir.mkdir(exist_ok=True)
    r = Renderer(scene, width, height_px)
    centres, names = [], []
    for i, (cam, target) in enumerate(orbit(n_frames, radius, height)):
        img, _ = r.render(cam, target)
        if blur_every and i % blur_every == blur_every - 1:
            from PIL import ImageFilter

            img = np.asarray(Image.fromarray(img).filter(ImageFilter.GaussianBlur(4)))
        name = f"frame_{i:04d}.png"
        Image.fromarray(img).save(frames_dir / name)
        centres.append(cam.tolist())
        names.append(name)
    if video:
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-framerate", str(fps), "-i", str(frames_dir / "frame_%04d.png"),
                        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "16", str(out_dir / "walkaround.mp4")], check=True)
    gt = GroundTruth(
        scene=scene.name, width=width, height=height_px, focal_px=float(r.f), camera_centres=centres, frame_names=names,
        targets={t.name: [t.center[0], t.center[1], 0.0] for t in scene.targets},
        boxes={b.name: {"center": list(b.center), "size": list(b.size)} for b in scene.boxes},
    )
    (out_dir / "ground_truth.json").write_text(json.dumps(asdict(gt), indent=2))
    return gt
