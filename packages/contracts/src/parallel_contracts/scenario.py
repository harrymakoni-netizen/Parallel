"""Scenario representation: proposed changes, assumptions and operating conditions."""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field, model_validator

from . import SCHEMA_VERSION
from .domain import CONTROLS_DISCIPLINE, Discipline, ScenarioControls
from .provenance import Assumption, Provenance, ProvenanceKind


class RunSettings(BaseModel):
    seed: int | None = Field(default=None, description="Random seed; required for stochastic engines")
    replications: int = Field(default=1, ge=1, le=200)
    timeout_s: int = Field(default=1800, ge=10, le=7 * 24 * 3600)
    solver: dict[str, Any] = Field(default_factory=dict)


class ScenarioContent(BaseModel):
    schema_version: Literal["1.0"] = SCHEMA_VERSION  # type: ignore[assignment]
    discipline: Discipline
    engine_id: str
    is_baseline: bool = False
    description: str = ""
    controls: ScenarioControls
    settings: RunSettings = Field(default_factory=RunSettings)
    assumptions: list[Assumption] = Field(default_factory=list)
    model_change_notes: list[str] = Field(
        default_factory=list,
        description="Human-readable account of how each control changes the underlying model (generated by the adapter).",
    )
    provenance: Provenance = Field(default_factory=lambda: Provenance(kind=ProvenanceKind.assumption))

    @model_validator(mode="after")
    def _controls_match(self) -> ScenarioContent:
        if CONTROLS_DISCIPLINE[self.controls.kind] != self.discipline:
            raise ValueError(f"controls of kind {self.controls.kind} do not belong to discipline {self.discipline}")
        return self
